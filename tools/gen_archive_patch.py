"""The in-memory archive patch (build/archive_patch.inc): the byte runs where the mod's versions of the game's two UI
archives differ from the originals, for resources.cpp to apply as the game loads them. Each run keeps a hash of the
original bytes (not the bytes themselves), so the patch only applies to the exact archives it was made from.

Inputs are the decompressed archives: the original blarc and bntx from the game, and the mod's versions made by
make_icons_romfs.py / make_icons_bntx.py.
usage: gen_archive_patch.py <orig blarc.zs> <mod blarc.zs> <ZsDic.pack.zs> <orig bntx.zs> <mod bntx.zs> <out .inc>"""
import sys, zstandard, oead
OB, MB, DIC, OT, MT, OUT = sys.argv[1:7]
dicts = {f.name: bytes(f.data) for f in oead.Sarc(zstandard.ZstdDecompressor().decompressobj().decompress(open(DIC, 'rb').read())).get_files()}
zd = zstandard.ZstdCompressionDict(dicts['zs.zsdic'])
dz = lambda p, d=None: (zstandard.ZstdDecompressor(dict_data=d) if d else zstandard.ZstdDecompressor()).decompressobj().decompress(open(p, 'rb').read())

def fnv(b):
    h = 0xcbf29ce484222325
    for x in b: h = ((h ^ x) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h

def runs(a, b, gap=16):
    assert len(a) == len(b)
    import numpy as np
    x = np.frombuffer(a, np.uint8) != np.frombuffer(b, np.uint8)
    idx = np.nonzero(x)[0]
    out = []
    for i in idx:
        i = int(i)
        if out and i - out[-1][1] <= gap: out[-1][1] = i + 1
        else: out.append([i, i + 1])
    return [(s, e - s) for s, e in out]

parts, blob = [], bytearray()
for name, o, m in (('Layout', dz(OB, zd), dz(MB, zd)), ('Textures', dz(OT), dz(MT))):
    rs = runs(o, m)
    rows = []
    for off, n in rs:
        rows.append('{%#x, %d, %#018xULL, %#018xULL, %d}' % (off, n, fnv(o[off:off + n]), fnv(m[off:off + n]), len(blob)))
        blob += m[off:off + n]
    parts.append((name, len(o), o[:4].decode(), rows))
    print(name, len(o), len(rs), 'runs,', sum(n for _, n in rs), 'bytes')
with open(OUT, 'w') as f:
    f.write('// generated by tools/gen_archive_patch.py - do not edit\n#pragma once\nnamespace mm::archive {\n')
    f.write('struct Run { u32 offset, length; u64 oldHash, newHash; u32 data; };\n')
    for name, size, magic, rows in parts:
        f.write('constexpr u32 k%sSize = %d;\nconstexpr char k%sMagic[5] = "%s";\n' % (name, size, name, magic))
        f.write('constexpr Run k%sRuns[] = {%s};\n' % (name, ', '.join(rows)))
    f.write('alignas(16) constexpr u8 kData[] = {%s};\n' % ','.join(str(x) for x in blob))
    f.write('}  // namespace mm::archive\n')
print('data', len(blob), 'bytes')
