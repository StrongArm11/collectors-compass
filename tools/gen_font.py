"""Bitmap font for the mod's menu and hints (build/font.inc): Inter SemiBold (SIL Open Font License 1.1, see
OFL-Inter.txt), rendered once at a 64-pixel size as 8-bit coverage; the module scales it down when it paints.

Characters: printable ASCII, plus a few symbols our strings write as bytes 0x80 and up:
  \\x80 up arrow, \\x81 down arrow, \\x82 left arrow, \\x83 right arrow, \\x84 bullet, \\x85 check mark (if the font has one)
usage: gen_font.py <font .otf> <output .inc>"""
import sys
from PIL import ImageFont

FONT, OUT = sys.argv[1], sys.argv[2]
SIZE = 64
EXTRA = ['↑', '↓', '←', '→', '•', '✓']
font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
chars = [chr(c) for c in range(32, 127)] + EXTRA
glyphs, data = [], bytearray()
for ch in chars:
    mask, (ox, oy) = font.getmask2(ch, mode='L')
    w, h = mask.size
    adv = font.getlength(ch)
    if ch != ' ' and (w == 0 or h == 0) and ch in EXTRA:   # not in the font: fall back to a bullet-free blank
        print('font has no', repr(ch))
    glyphs.append((len(data), w, h, ox, oy, round(adv * 16)))
    data += bytes(mask)
with open(OUT, 'w') as f:
    f.write('// generated by tools/gen_font.py from Inter SemiBold (SIL Open Font License 1.1) - do not edit\n#pragma once\n')
    f.write('namespace mm::font {\n')
    f.write(f'constexpr int kSize = {SIZE};      // pixel size the glyphs were rendered at\n')
    f.write(f'constexpr int kAscent = {ascent}, kDescent = {descent};\n')
    f.write(f'constexpr int kFirst = 32, kCount = {len(chars)};   // ASCII 32..126, then the extra symbols from 0x80\n')
    f.write('struct Glyph { u32 offset; u8 width, height; s8 left, top; u16 advance16; };   // advance in 1/16 pixel\n')
    f.write('constexpr Glyph kGlyphs[] = {\n' + '\n'.join(
        f'    {{{o}, {w}, {h}, {ox}, {oy}, {a}}},  // {ch!r}' for (o, w, h, ox, oy, a), ch in zip(glyphs, chars)) + '\n};\n')
    f.write(f'alignas(16) constexpr u8 kCoverage[{len(data)}] = {{\n')
    for i in range(0, len(data), 40):
        f.write('    ' + ','.join(str(b) for b in data[i:i + 40]) + ',\n')
    f.write('};\n}  // namespace mm::font\n')
print(f'font: {len(chars)} glyphs, {len(data)} bytes of coverage, ascent {ascent}, descent {descent}')
